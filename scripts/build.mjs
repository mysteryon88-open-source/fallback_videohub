import { readFile, writeFile } from "node:fs/promises";

const files = ["i18n.js", "layout.js", "photos.js", "png-dpi.js", "pdf.js", "renderer.js", "export.js", "app.js"];
const moduleId = file => file.replace(/\.js$/, "").replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
const indent = source => source.split("\n").map(line => line ? `    ${line}` : "").join("\n");
const modules = [];

for (const file of files) {
  const exported = [];
  let source = await readFile(new URL(`../src/${file}`, import.meta.url), "utf8");
  source = source.replace(
    /^import\s+\{\s*([^}]+?)\s*\}\s+from\s+"\.\/([^"]+)";\r?\n?/gm,
    (_, names, dependency) => `const { ${names.replace(/\s+/g, " ").trim()} } = modules.${moduleId(dependency)};\n`
  );
  source = source.replace(
    /^export\s+(const|class|async function|function)\s+([A-Za-z_$][\w$]*)/gm,
    (_, declaration, name) => {
      exported.push(name);
      return `${declaration} ${name}`;
    }
  ).trim();

  modules.push(file === "app.js"
    ? `  (() => {\n${indent(source)}\n  })();`
    : `  modules.${moduleId(file)} = (() => {\n${indent(source)}\n\n    return { ${exported.join(", ")} };\n  })();`);
}

const bundle = `// Generated by npm run build. Edit src/*.js instead.\n(() => {\n  "use strict";\n  const modules = {};\n\n${modules.join("\n\n")}\n})();\n`;
const output = new URL("../photo-sheet.js", import.meta.url);

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== bundle) throw new Error("photo-sheet.js is missing or stale. Run npm run build.");
} else {
  await writeFile(output, bundle);
}
